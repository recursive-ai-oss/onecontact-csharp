#!/usr/bin/env python3
"""Writes src/OneContact.Extraction/Text/NameLists.cs: the most common US given names and family names, as the reader of free text uses
them to tell a person from other capitalized words.

usage: extraction-lists.py <names data dir> <output .cs>
  The data dir holds census/names.zip (2010 Census surnames file B, public domain) and ssa/names.zip (SSA national baby names, public
  domain); see pins/names.pin for their hashes. Both are US government works (17 U.S.C. 105).
Given names: summed over births from 1940 on, both sexes, the commonest first, ASCII letters only, three letters or more, minus words
that are far more often something else. Family names: the 2010 Census rank order, ASCII only, three letters or more.
"""
import csv
import io
import re
import sys
import zipfile
from collections import Counter

GIVEN = 2200
SURNAMES = 5000
# Given names that are first a place, a common word or a title in running text.
NOT_GIVEN = set("""
austin dallas london paris florence sydney brooklyn carolina georgia virginia jordan chase cash hunter major king prince princess queen royal
lane summer autumn winter april may june july august hope joy faith grace honor liberty harmony bella angel unique precious sunny sky
storm rain river forest ocean lake island heaven paradise destiny genesis legend legacy champion kingston london madison jackson
washington lincoln kennedy franklin jefferson hamilton harrison monroe roosevelt dakota montana sierra aspen sage rowan ivy rose lily
daisy violet iris hazel olive ruby pearl jade amber crystal diamond opal coral ash ember blaze flint stone rock cliff dale glen
bishop deacon pastor judge sheriff colonel captain general sergeant admiral baron duke earl lord sir
miles mark will bill rich frank sue pat don art ray jack bob rob dan sam tom tim joe jim max ben ted tony van
""".split())
WORD = re.compile(r"^[a-z]{3,}$")


def main(data, out):
    given = Counter()
    with zipfile.ZipFile(f"{data}/ssa/names.zip") as z:
        for name in z.namelist():
            m = re.fullmatch(r"yob(\d{4})\.txt", name)
            if not m or int(m.group(1)) < 1940:
                continue
            for line in io.TextIOWrapper(z.open(name), encoding="utf-8"):
                n, _sex, c = line.strip().split(",")
                n = n.lower()
                if WORD.match(n):
                    given[n] += int(c)
    given_names = [n for n, _ in given.most_common() if n not in NOT_GIVEN][:GIVEN]

    surnames = []
    with zipfile.ZipFile(f"{data}/census/names.zip") as z:
        with io.TextIOWrapper(z.open("Names_2010Census.csv"), encoding="utf-8") as f:
            for row in csv.DictReader(f):
                n = row["name"].lower()
                if WORD.match(n) and n != "all other names":
                    surnames.append(n)
                if len(surnames) == SURNAMES:
                    break

    def block(words):
        lines, cur = [], ""
        for w in words:
            if len(cur) + len(w) > 110:
                lines.append(cur.rstrip())
                cur = ""
            cur += w + " "
        lines.append(cur.rstrip())
        return "\n".join("        " + l for l in lines)

    with open(out, "w", encoding="utf-8", newline="\n") as o:
        o.write(
            "// Generated by tools/data/names/extraction-lists.py from the US Census 2010 surnames file and the SSA national baby names\n"
            "// (both US government works, public domain). Do not edit by hand.\n"
            "namespace RecursiveAI.OneContact.Extraction.Text;\n\n"
            "internal static class NameListData\n{\n"
            f"    /// <summary>The {len(given_names)} commonest given names, commonest first, lower case.</summary>\n"
            '    internal const string GivenNames = """\n' + block(given_names) + '\n        """;\n\n'
            f"    /// <summary>The {len(surnames)} commonest family names, commonest first, lower case.</summary>\n"
            '    internal const string FamilyNames = """\n' + block(surnames) + '\n        """;\n}\n'
        )


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
